import { readFileSync } from 'node:fs';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { render, screen, waitFor } from '@testing-library/react';
import { provenanceLines } from '@/lib/widgetProvenance';
import { getWidgetExportData, type WidgetDataPayload } from '@/lib/widgetRuntime';
import type { EquityHistoricalResponse } from '@/types/equity';
import { ATRRegimeWidget } from './ATRRegimeWidget';

jest.mock('@/lib/env', () => ({ env: { apiUrl: 'https://api.example.test' } }));
jest.mock('@/lib/supabase', () => ({ isSupabaseConfigured: false, supabase: null }));

const fixturePath = process.env.VNIBB_HISTORY_CONTRACT_REPLAY;
const itWithRouteOutput = fixturePath ? it : it.skip;

itWithRouteOutput.each(['unresolved', 'replaced'] as const)('renders actual historical route output: %s', async (kind) => {
  // Generated by the ASGI test, not fabricated missing-session metadata.
  const payloads: Record<typeof kind, EquityHistoricalResponse> = JSON.parse(readFileSync(fixturePath!, 'utf8'));
  const originalFetch = globalThis.fetch;
  const fetchReplay = jest.fn(async () => ({ ok: true, json: async () => payloads[kind] }) as Response);
  globalThis.fetch = fetchReplay;
  const publish = jest.fn<void, [WidgetDataPayload]>();
  const client = new QueryClient({ defaultOptions: { queries: { retry: false, gcTime: Infinity } } });
  try {
    render(<QueryClientProvider client={client}><ATRRegimeWidget symbol="XYZ" onDataChange={publish} /></QueryClientProvider>);
    if (kind === 'unresolved') {
      expect(await screen.findByText('ATR regime unavailable')).toBeInTheDocument();
      expect(screen.queryByText('Sizing Model')).not.toBeInTheDocument();
    } else {
      expect(await screen.findByText('Sizing Model')).toBeInTheDocument();
      expect(screen.getByText(/40 consecutive sessions/)).toBeInTheDocument();
      expect(screen.getByText('Suggested Shares')).toBeInTheDocument();
    }
    expect(fetchReplay).toHaveBeenCalledWith(expect.stringContaining('/api/v1/equity/historical?'), expect.anything());
    const status = kind === 'unresolved' ? 'unavailable' : 'available';
    await waitFor(() => expect(getWidgetExportData(publish.mock.lastCall?.[0])).toMatchObject({ status }));
    const runtime = publish.mock.lastCall?.[0].__widgetRuntime;
    expect(getWidgetExportData(publish.mock.lastCall?.[0])).toMatchObject(kind === 'unresolved' ? {
      atr: null, rank: null, suggestedShares: null, unresolvedExcludedDates: ['2026-07-01'],
    } : {
      admittedSessions: 40, historyCount: 27, atr: 40, replacedExcludedDates: ['2026-07-01'],
    });
    expect(provenanceLines(runtime?.provenance)).toEqual(expect.arrayContaining([
      ['observation_status', status], ['source_as_of', '2026-07-31'],
      ['gap_sessions', kind === 'unresolved' ? '1' : '0'],
    ]));
    if (kind === 'unresolved') {
      expect(provenanceLines(runtime?.provenance)).toContainEqual([
        'admission_reason', 'Unresolved interior sessions prevent consecutive true ranges.',
      ]);
    }
  } finally {
    globalThis.fetch = originalFetch;
    client.clear();
  }
});