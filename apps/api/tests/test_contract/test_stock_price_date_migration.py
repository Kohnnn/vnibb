@pytest.mark.asyncio
@pytest.mark.parametrize(
    "case, definition",
    [
        ("absent", None),
        ("wrong_table", "ON other_prices (time)"),
        ("wrong_method", "ON stock_prices USING hash (time)"),
        ("wrong_column", "ON stock_prices (symbol)"),
        ("multiple_keys", "ON stock_prices (time, symbol)"),
        ("included_column", "ON stock_prices (time) INCLUDE (symbol)"),
        ("partial", "ON stock_prices (time) WHERE interval = '1D'"),
        ("expression", "ON stock_prices ((time + 1))"),
        ("unique", "ON stock_prices (time)"),
        ("invalid", None),
    ],
)
async def test_stock_price_date_index_preserves_rows_and_rejects_unsafe_indexes(
    stock_prices, case, definition
):
    engine, connection, schema = stock_prices
    if definition is not None:
        if case == "wrong_table":
            await connection.execute(text("CREATE TABLE other_prices (time date)"))
        unique = "UNIQUE " if case == "unique" else ""
        await connection.execute(text(
            f"CREATE {unique}INDEX ix_stock_price_date_only {definition}"
        ))
        await connection.commit()
    if case == "invalid":
        async with engine.connect() as blocker:
            await blocker.execute(text(f"SET search_path TO {schema}"))
            await blocker.execute(text("LOCK TABLE stock_prices IN ROW EXCLUSIVE MODE"))
            isolation = await connection.get_isolation_level()
            await connection.execution_options(isolation_level="AUTOCOMMIT")
            try:
                await connection.execute(text("SET lock_timeout = '100ms'"))
                with pytest.raises(DBAPIError, match="lock timeout"):
                    await connection.execute(text(
                        "CREATE INDEX CONCURRENTLY ix_stock_price_date_only ON stock_prices (time)"
                    ))
            finally:
                await connection.execute(text("SET lock_timeout = '7s'"))
                await connection.rollback()
                await connection.execution_options(isolation_level=isolation)
        invalid = (await connection.execute(text(
            "SELECT indisvalid, indisready FROM pg_index "
            "WHERE indexrelid = 'ix_stock_price_date_only'::regclass"
        ))).one()
        assert not invalid.indisvalid or not invalid.indisready

    original_rows = (await connection.execute(text(ROWS))).all()
    original_indexes = (await connection.execute(text(INDEXES))).all()
    original_max_dates = (await connection.execute(text(MAX_DATES))).one()
    original_timeouts = (await connection.execute(text(TIMEOUTS))).one()
    assert original_max_dates == (date(2026, 10, 24), date(2026, 10, 23))
    await connection.commit()

    if case == "absent":
        await connection.run_sync(apply_migration)
        restored_indexes = (await connection.execute(text(INDEXES))).all()
        assert len(restored_indexes) == len(original_indexes) + 1
        assert all(index in restored_indexes for index in original_indexes)
        await connection.commit()
        await connection.run_sync(apply_migration)
        assert (await connection.execute(text(INDEXES))).all() == restored_indexes
    else:
        with pytest.raises(RuntimeError, match="explicit schema review required"):
            await connection.run_sync(apply_migration)
        assert (await connection.execute(text(INDEXES))).all() == original_indexes

    assert (await connection.execute(text(ROWS))).all() == original_rows
    assert (await connection.execute(text(MAX_DATES))).one() == original_max_dates
    assert (await connection.execute(text(TIMEOUTS))).one() == original_timeouts
