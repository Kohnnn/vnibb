import importlib.util
import os
from datetime import date
from pathlib import Path
from uuid import uuid4

import pytest
from alembic.migration import MigrationContext
from alembic.operations import Operations
from sqlalchemy import text
from sqlalchemy.exc import DBAPIError
from sqlalchemy.ext.asyncio import create_async_engine

pytestmark = [
    pytest.mark.postgres_contract,
    pytest.mark.skipif(
        os.environ.get("POSTGRES_CONTRACT") != "1",
        reason="requires a disposable PostgreSQL contract database",
    ),
]

ROWS = "SELECT id, symbol, time, interval, close FROM stock_prices ORDER BY id"
INDEXES = """
    SELECT c.oid, pg_get_indexdef(c.oid), i.indisvalid, i.indisready
    FROM pg_class c JOIN pg_index i ON i.indexrelid = c.oid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = current_schema() ORDER BY c.oid
"""
MAX_DATES = """
    SELECT (SELECT max(time) FROM stock_prices),
           (SELECT max(time) FROM stock_prices WHERE interval = '1D')
"""
TIMEOUTS = "SELECT current_setting('lock_timeout'), current_setting('statement_timeout')"


def apply_migration(connection):
    path = (
        Path(__file__).parents[2]
        / "migrations/versions/20261024_1200_restore_stock_price_date_index.py"
    )
    spec = importlib.util.spec_from_file_location("restore_stock_price_date_index", path)
    assert spec is not None and spec.loader is not None
    migration = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(migration)
    context = MigrationContext.configure(connection)
    with context.begin_transaction():
        with Operations.context(context):
            migration.upgrade()


