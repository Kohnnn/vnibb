@pytest.mark.asyncio
@pytest.mark.parametrize(
    "case,definition",
    [
        ("absent", None),
        ("valid", "CREATE UNIQUE INDEX ix_stocks_symbol ON stocks (symbol)"),
        ("wrong_table", "CREATE UNIQUE INDEX ix_stocks_symbol ON other_stocks (symbol)"),
        ("wrong_method", "CREATE INDEX ix_stocks_symbol ON stocks USING hash (symbol)"),
        ("wrong_column", "CREATE UNIQUE INDEX ix_stocks_symbol ON stocks (id)"),
        ("nonunique", "CREATE INDEX ix_stocks_symbol ON stocks (symbol)"),
        ("multiple_keys", "CREATE UNIQUE INDEX ix_stocks_symbol ON stocks (symbol, id)"),
        ("included_column", "CREATE UNIQUE INDEX ix_stocks_symbol ON stocks (symbol) INCLUDE (id)"),
        ("partial", "CREATE UNIQUE INDEX ix_stocks_symbol ON stocks (symbol) WHERE is_active = 1"),
        ("expression", "CREATE UNIQUE INDEX ix_stocks_symbol ON stocks (lower(symbol))"),
        ("invalid", None),
        ("duplicates", None),
    ],
)
async def test_stock_symbol_key_preserves_rows_and_rejects_unsafe_indexes(stocks, case, definition):
    engine, connection, schema = stocks
    if case == "wrong_table":
        await connection.execute(text("CREATE TABLE other_stocks (symbol varchar(10))"))
    if definition is not None:
        await connection.execute(text(definition))
        await connection.commit()
    if case == "duplicates":
        await connection.execute(text("INSERT INTO stocks (symbol, exchange) VALUES ('VNM', 'HNX')"))
        await connection.commit()
    if case == "invalid":
        async with engine.connect() as blocker:
            await blocker.execute(text(f"SET search_path TO {schema}"))
            await blocker.execute(text("LOCK TABLE stocks IN ROW EXCLUSIVE MODE"))
            isolation = await connection.get_isolation_level()
            await connection.execution_options(isolation_level="AUTOCOMMIT")
            try:
                await connection.execute(text("SET lock_timeout = '100ms'"))
                with pytest.raises(DBAPIError, match="lock timeout"):
                    await connection.execute(text(
                        "CREATE UNIQUE INDEX CONCURRENTLY ix_stocks_symbol ON stocks (symbol)"
                    ))
            finally:
                await connection.execute(text("SET lock_timeout = '7s'"))
                await connection.rollback()
                await connection.execution_options(isolation_level=isolation)

    original_rows = (await connection.execute(text(ROWS))).all()
    original_indexes = (await connection.execute(text(INDEXES))).all()
    original_timeouts = (await connection.execute(text(TIMEOUTS))).one()
    await connection.commit()
    if case in {"absent", "valid"}:
        await connection.run_sync(apply_migration)
        restored = (await connection.execute(text(INDEXES))).all()
        assert len(restored) == len(original_indexes) + (case == "absent")
        assert all(index in restored for index in original_indexes)
        await connection.commit()
        await connection.run_sync(apply_migration)
        assert (await connection.execute(text(INDEXES))).all() == restored
    elif case == "duplicates":
        with pytest.raises(DBAPIError) as caught:
            await connection.run_sync(apply_migration)
        assert caught.value.orig.sqlstate == "23505"
        failed = (await connection.execute(text(
            "SELECT indisvalid FROM pg_index WHERE indexrelid = 'ix_stocks_symbol'::regclass"
        ))).scalar_one()
        assert not failed
        await connection.commit()
        with pytest.raises(RuntimeError, match="explicit schema review required"):
            await connection.run_sync(apply_migration)
    else:
        with pytest.raises(RuntimeError, match="explicit schema review required"):
            await connection.run_sync(apply_migration)
        assert (await connection.execute(text(INDEXES))).all() == original_indexes
    assert (await connection.execute(text(ROWS))).all() == original_rows
    assert (await connection.execute(text(TIMEOUTS))).one() == original_timeouts


@pytest.mark.asyncio
async def test_restored_stock_key_accepts_actual_listing_writer_without_duplicate_rows(stocks):
    from vnibb.services.cache_manager import CacheManager

    _, connection, _ = stocks
    before_ids = (await connection.execute(text("SELECT symbol, id FROM stocks ORDER BY symbol"))).all()
    await connection.commit()
    await connection.run_sync(apply_migration)
    async with AsyncSession(bind=connection) as session:
        cache = CacheManager(db=session)
        rows = [{"symbol": "VNM", "exchange": "HOSE", "company_name": "Updated name"}]
        assert await cache.store_listing_data(rows, source="vietcap") == 1
        assert await cache.store_listing_data(rows, source="vietcap") == 1
    assert (await connection.execute(text("SELECT symbol, id FROM stocks ORDER BY symbol"))).all() == before_ids
    assert (await connection.execute(text("SELECT company_name FROM stocks WHERE symbol='VNM'"))).scalar_one() == "Updated name"
