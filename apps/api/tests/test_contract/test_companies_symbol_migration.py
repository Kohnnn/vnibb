pytestmark = [
    pytest.mark.postgres_contract,
    pytest.mark.skipif(
        os.environ.get("POSTGRES_CONTRACT") != "1",
        reason="requires a disposable PostgreSQL contract database",
    ),
]


def apply_migration(connection):
    path = (
        Path(__file__).parents[2]
        / "migrations/versions/20261023_1200_restore_companies_symbol_index.py"
    )
    spec = importlib.util.spec_from_file_location("restore_companies_symbol_index", path)
    assert spec is not None and spec.loader is not None
    migration = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(migration)
    with Operations.context(MigrationContext.configure(connection)):
        migration.upgrade()


@pytest.mark.asyncio
@pytest.mark.parametrize("duplicate", [False, True])
async def test_companies_index_repair_preserves_identity_rows_and_references(duplicate):
    from conftest import postgres_contract_database_url

    engine = create_async_engine(postgres_contract_database_url())
    schema = f"companies_migration_{uuid4().hex}"
    try:
        async with engine.connect() as connection:
            await connection.execute(text(f"CREATE SCHEMA {schema}"))
            await connection.execute(text(f"SET search_path TO {schema}"))
            await connection.execute(text("""
                CREATE TABLE companies (
                    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    symbol varchar(10) NOT NULL,
                    company_name varchar(255), short_name varchar(100), english_name varchar(255),
                    exchange varchar(10), industry varchar(100), sector varchar(100),
                    subsector varchar(100), established_date date, listing_date date,
                    outstanding_shares double precision, listed_shares double precision,
                    website varchar(255), email varchar(100), phone varchar(50), fax varchar(50),
                    address text, business_description text, raw_data json,
                    created_at timestamp NOT NULL, updated_at timestamp NOT NULL
                )
            """))
            await connection.execute(text("""
                INSERT INTO companies (symbol, company_name, created_at, updated_at)
                VALUES ('VNM', 'Original', '2020-01-01', '2020-01-01'),
                       ('FPT', 'Other', '2020-01-01', '2020-01-01')
            """))
            await connection.execute(text(
                "CREATE TABLE shareholders (company_id integer REFERENCES companies(id))"
            ))
            await connection.execute(text(
                "CREATE TABLE officers (company_id integer REFERENCES companies(id))"
            ))
            await connection.execute(text("INSERT INTO shareholders VALUES (1)"))
            await connection.execute(text("INSERT INTO officers VALUES (2)"))
            if duplicate:
                await connection.execute(text("""
                    INSERT INTO companies (symbol, company_name, created_at, updated_at)
                    VALUES ('VNM', 'Duplicate', '2020-01-01', '2020-01-01')
                """))
            await connection.commit()

            async with AsyncSession(bind=connection, expire_on_commit=False) as session:
                assert await CacheManager(session).store_profile_data(
                    "VNM", {"company_name": "Rejected"}
                ) is False

            original = (await connection.execute(text(
                "SELECT id, symbol, company_name, created_at FROM companies ORDER BY id"
            ))).all()
            sequence_before = (await connection.execute(text(
                "SELECT last_value, is_called FROM companies_id_seq"
            ))).one()
            await connection.commit()

            if duplicate:
                with pytest.raises(RuntimeError, match="null, noncanonical or duplicated"):
                    async with connection.begin():
                        await connection.run_sync(apply_migration)
            else:
                async with connection.begin():
                    await connection.run_sync(apply_migration)
                async with connection.begin():
                    await connection.run_sync(apply_migration)

            assert (await connection.execute(text(
                "SELECT id, symbol, company_name, created_at FROM companies ORDER BY id"
            ))).all() == original
            assert (await connection.execute(text(
                "SELECT last_value, is_called FROM companies_id_seq"
            ))).one() == sequence_before
            assert (await connection.execute(text(
                "SELECT attidentity::text FROM pg_attribute "
                "WHERE attrelid='companies'::regclass AND attname='id'"
            ))).scalar_one() == "d"
            assert (await connection.execute(text(
                "SELECT company_id FROM shareholders"
            ))).scalars().all() == [1]
            assert (await connection.execute(text(
                "SELECT company_id FROM officers"
            ))).scalars().all() == [2]
            await connection.commit()

            async with AsyncSession(bind=connection, expire_on_commit=False) as session:
                stored = await CacheManager(session).store_profile_data(
                    "vnm", {"company_name": "Updated"}
                )
                assert stored is (not duplicate)
            if not duplicate:
                async def insert_profile():
                    async with engine.connect() as writer:
                        await writer.execute(text(f"SET search_path TO {schema}"))
                        await writer.commit()
                        async with AsyncSession(bind=writer) as session:
                            return await CacheManager(session).store_profile_data(
                                "vcb", {"company_name": "New", "outstanding_shares": 0}
                            )

                assert await asyncio.gather(insert_profile(), insert_profile()) == [True, True]
            rows = (await connection.execute(text(
                "SELECT id, symbol, company_name FROM companies ORDER BY id"
            ))).all()
            if duplicate:
                assert rows == [(1, "VNM", "Original"), (2, "FPT", "Other"), (3, "VNM", "Duplicate")]
            else:
                assert rows[:2] == [(1, "VNM", "Updated"), (2, "FPT", "Other")]
                assert len(rows) == 3
                assert rows[2].id > 2
                assert rows[2].symbol == "VCB"
                assert rows[2].company_name == "New"
                assert (await connection.execute(text(
                    "SELECT outstanding_shares FROM companies WHERE symbol='VCB'"
                ))).scalar_one() is None
    finally:
        async with engine.begin() as cleanup:
            await cleanup.execute(text(f"DROP SCHEMA IF EXISTS {schema} CASCADE"))
        await engine.dispose()


@pytest.mark.asyncio
@pytest.mark.parametrize(
    "case, symbols, nullable, expected",
    [
        ("nullable", ["VNM"], True, "must be NOT NULL"),
        ("null", [None], True, "must be NOT NULL"),
        ("blank", [""], False, "noncanonical"),
        ("lowercase", ["vnm"], False, "noncanonical"),
        ("trimmed", [" VNM"], False, "noncanonical"),
        ("normalized_duplicate", ["VNM", "vnm"], False, "noncanonical"),
        ("deferrable", ["VNM"], False, "Deferrable"),
    ],
)
async def test_companies_repair_rejects_unsafe_existing_unique_keys(
    case, symbols, nullable, expected
):
    from conftest import postgres_contract_database_url

    engine = create_async_engine(postgres_contract_database_url())
    schema = f"companies_guard_{uuid4().hex}"
    try:
        async with engine.connect() as connection:
            await connection.execute(text(f"CREATE SCHEMA {schema}"))
            await connection.execute(text(f"SET search_path TO {schema}"))
            nullability = "" if nullable else "NOT NULL"
            await connection.execute(text(
                "CREATE TABLE companies (id integer GENERATED BY DEFAULT AS IDENTITY "
                f"PRIMARY KEY, symbol varchar(10) {nullability})"
            ))
            for symbol in symbols:
                await connection.execute(text(
                    "INSERT INTO companies (symbol) VALUES (:symbol)"
                ), {"symbol": symbol})
            await connection.execute(text(
                "CREATE UNIQUE INDEX existing_symbol_key ON companies (symbol)"
            ))
            if case == "deferrable":
                await connection.execute(text(
                    "ALTER TABLE companies ADD CONSTRAINT deferred_symbol_key "
                    "UNIQUE (symbol) DEFERRABLE INITIALLY IMMEDIATE"
                ))
            original = (await connection.execute(text(
                "SELECT id, symbol FROM companies ORDER BY id"
            ))).all()
            indexes = (await connection.execute(text(
                "SELECT indexrelid, pg_get_indexdef(indexrelid) FROM pg_index "
                "WHERE indrelid='companies'::regclass ORDER BY indexrelid"
            ))).all()
            sequence = (await connection.execute(text(
                "SELECT last_value, is_called FROM companies_id_seq"
            ))).one()
            await connection.commit()

            with pytest.raises(RuntimeError, match=expected):
                async with connection.begin():
                    await connection.run_sync(apply_migration)

            assert (await connection.execute(text(
                "SELECT id, symbol FROM companies ORDER BY id"
            ))).all() == original
            assert (await connection.execute(text(
                "SELECT indexrelid, pg_get_indexdef(indexrelid) FROM pg_index "
                "WHERE indrelid='companies'::regclass ORDER BY indexrelid"
            ))).all() == indexes
            assert (await connection.execute(text(
                "SELECT last_value, is_called FROM companies_id_seq"
            ))).one() == sequence
    finally:
        async with engine.begin() as cleanup:
            await cleanup.execute(text(f"DROP SCHEMA IF EXISTS {schema} CASCADE"))
        await engine.dispose()
