"""PostgreSQL migration contract for old and new snapshot writers."""

from __future__ import annotations

import importlib.util
import os
from datetime import UTC, datetime
from pathlib import Path
from uuid import uuid4

import pytest
from alembic.migration import MigrationContext
from alembic.operations import Operations
from sqlalchemy import create_engine, text
from sqlalchemy.exc import IntegrityError


@pytest.mark.skipif(
    os.environ.get("POSTGRES_CONTRACT") != "1",
    reason="requires a disposable PostgreSQL contract database",
)
def test_bucket_migration_accepts_legacy_and_new_writers_and_downgrades():
    from conftest import postgres_contract_database_url

    migration_path = (
        Path(__file__).parents[2]
        / "migrations/versions/20260926_1200_bound_prediction_snapshots.py"
    )
    spec = importlib.util.spec_from_file_location("bound_prediction_snapshots", migration_path)
    assert spec is not None and spec.loader is not None
    migration = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(migration)

    url = postgres_contract_database_url().replace("+asyncpg", "+psycopg")
    engine = create_engine(url)
    schema = f"snapshot_migration_{uuid4().hex}"
    try:
        with engine.connect() as conn:
            conn.execute(text(f"CREATE SCHEMA {schema}"))
            conn.commit()
            conn.execute(text(f"SET search_path TO {schema}"))
            conn.execute(text("""
                CREATE TABLE prediction_markets (
                    id integer PRIMARY KEY, source text NOT NULL, source_id text NOT NULL,
                    updated_at timestamptz
                )
            """))
            for table in ("prediction_market_snapshots", "prediction_market_intraday_snapshots"):
                conn.execute(text(f"""
                    CREATE TABLE {table} (
                        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        source text NOT NULL, source_id text NOT NULL,
                        captured_at timestamptz NOT NULL DEFAULT now()
                    )
                """))
            conn.execute(text("""
                INSERT INTO prediction_market_snapshots (source, source_id, captured_at)
                VALUES ('polymarket', 'before-upgrade', '2026-09-26 23:59:00+07')
            """))
            conn.commit()

            # Alembic commits this DDL before CREATE INDEX CONCURRENTLY.
            context = MigrationContext.configure(conn)
            with Operations.context(context), context.begin_transaction():
                migration._add_snapshot_buckets()
            with engine.begin() as old_writer:
                old_writer.execute(text(f"SET search_path TO {schema}"))
                for table in ("prediction_market_snapshots", "prediction_market_intraday_snapshots"):
                    old_writer.execute(text(f"""
                        INSERT INTO {table} (source, source_id, captured_at)
                        VALUES ('polymarket', 'during-index-build', '2026-09-26 23:42:00+07')
                    """))

            context = MigrationContext.configure(conn)
            with Operations.context(context), context.begin_transaction():
                migration.upgrade()
            # Concurrent index DDL committed the column and trigger before the writer resumes.
            conn.commit()
            with conn.begin():
                assert conn.scalar(text("""
                    SELECT bucket_at FROM prediction_market_snapshots
                    WHERE source_id = 'before-upgrade'
                """)) == datetime(2026, 9, 26, tzinfo=UTC)
                assert conn.scalar(text("""
                    SELECT bucket_at FROM prediction_market_intraday_snapshots
                    WHERE source_id = 'during-index-build'
                """)) == datetime(2026, 9, 26, 16, 30, tzinfo=UTC)
                for table, expected in (
                    ("prediction_market_snapshots", datetime(2026, 9, 26, tzinfo=UTC)),
                    ("prediction_market_intraday_snapshots", datetime(2026, 9, 26, 16, 30, tzinfo=UTC)),
                ):
                    # Old images omit bucket_at, while new images explicitly provide it.
                    conn.execute(text(f"""
                        INSERT INTO {table} (source, source_id, captured_at)
                        VALUES ('polymarket', 'legacy', '2026-09-26 23:42:00+07')
                    """))
                    conn.execute(text(f"""
                        INSERT INTO {table} (source, source_id, captured_at, bucket_at)
                        VALUES ('polymarket', 'new', '2026-09-26 23:42:00+07',
                                '2026-09-26 00:00:00+00')
                    """))
                    assert conn.execute(text(f"""
                        SELECT source_id, bucket_at FROM {table}
                        WHERE source_id IN ('legacy', 'new') ORDER BY source_id
                    """)).all() == [("legacy", expected), ("new", expected)]
                    conn.execute(text(f"""
                        UPDATE {table} SET captured_at = '2026-09-27 00:02:00+07'
                        WHERE source_id = 'legacy'
                    """))
                    next_bucket = (
                        datetime(2026, 9, 26, tzinfo=UTC)
                        if table == "prediction_market_snapshots"
                        else datetime(2026, 9, 26, 17, 0, tzinfo=UTC)
                    )
                    assert conn.scalar(text(f"""
                        SELECT bucket_at FROM {table} WHERE source_id = 'legacy'
                    """)) == next_bucket
                    with pytest.raises(IntegrityError), conn.begin_nested():
                        conn.execute(text(f"""
                            INSERT INTO {table} (source, source_id, captured_at)
                            VALUES ('polymarket', 'new', '2026-09-26 23:44:00+07')
                        """))
                    # The old writer's insert is allowed again in another bucket.
                    conn.execute(text(f"""
                        INSERT INTO {table} (source, source_id, captured_at)
                        VALUES ('polymarket', 'new', '2026-09-28 00:02:00+07')
                    """))

            context = MigrationContext.configure(conn)
            with Operations.context(context), context.begin_transaction():
                migration.downgrade()
            assert conn.scalar(text("""
                SELECT count(*) FROM information_schema.triggers
                WHERE trigger_schema = current_schema() AND trigger_name LIKE 'trg_prediction_market_%_bucket_at'
            """)) == 0
            assert conn.scalar(text("""
                SELECT count(*) FROM information_schema.columns
                WHERE table_schema = current_schema() AND column_name = 'bucket_at'
            """)) == 0
            for table in ("prediction_market_snapshots", "prediction_market_intraday_snapshots"):
                conn.execute(text(f"""
                    INSERT INTO {table} (source, source_id, captured_at)
                    VALUES ('polymarket', 'after-downgrade', now())
                """))
            assert conn.scalar(text("""
                SELECT count(*) FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
                WHERE n.nspname = current_schema() AND p.proname = 'set_prediction_market_snapshot_bucket_at'
            """)) == 0
            conn.rollback()
    finally:
        with engine.begin() as cleanup:
            cleanup.execute(text(f"DROP SCHEMA {schema} CASCADE"))
        engine.dispose()
